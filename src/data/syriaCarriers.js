// شركات الشحن الرسمية لسوريا (قائمة الجدول بتاريخ 29 تشرين الأول 2026) + مطابقة الصيغ القديمة — منطق صرف بلا اعتماديات (قابل للاختبار بـnode).
// ترتيب الطباعة المعتمد — الأولوية الست، ثم «الباقي» (شركات معتمدة أخرى، غير
// مذكورة هنا)، ثم «أخرى» دائماً أخيراً.
export const SYRIA_SHIPPING_PRIORITY = ['قدموس', 'مسارات', 'مشوار', 'توصيل جرمانا', 'الكرم', 'العودة', 'ايزلا', 'بابل', 'صلة'];

// مطابقة مرنة لالتقاط الصيغ القديمة المخزَّنة بطلبات سابقة (كرم/شركة الكرم،
// بابل اكسبرس، توصيل ميتور، مسافات زائدة...) تحت شركتها الصحيحة — تُستخدم فقط
// وقت الطباعة/الفرز، ولا تُعدِّل القيمة المحفوظة بالطلب نفسه أبداً.
export const SYRIA_ALIAS_PATTERNS = {
  'قدموس':        /قدموس/i,
  'مسارات':       /مسارات/i,
  'مشوار':        /مشوار|موتور|ميتور/i, // «الموتور» القديمة = مشوار (توصيل الشام وريفها)
  'توصيل جرمانا': /جرمانا/i,
  'الكرم':        /كرم/i,
  'العودة':       /العودة/i,
  'ايزلا':        /ايزلا|إيزلا/i,
  'بابل':         /بابل|babel/i,
  'صلة':          /صل[ةه]/i,
};

/** اسم الشركة الرسمي لنص مخزَّن بصيغة قديمة/مختلفة (سوريا)، أو null إن لم يطابق أي شركة رسمية. */
export function syriaOfficialCarrier(raw) {
  const s = String(raw ?? '').trim();
  if (!s) return null;
  for (const canon of SYRIA_SHIPPING_PRIORITY) if (SYRIA_ALIAS_PATTERNS[canon].test(s)) return canon;
  return null;
}
