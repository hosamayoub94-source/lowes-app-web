// =============================================================
// حالات تكلفة الصنف في محرر الأسعار والتكاليف (دوال/ثوابت صرفة، بلا React).
//  • market/unified: تكلفة معتمدة (خاصة بالسوق أو موحّدة).
//  • missing: لا تكلفة مسجّلة.
//  • conflict: أكثر من تكلفة مختلفة لنفس فترة السريان (D-176) — لا تُختار أيٌّ منها بانتظار قرار المالك؛
//    تُعرض بوضوح ولا تُعامَل «ناقصة» كي لا يُظنّ أن لا تكلفة مسجّلة أصلاً.
// =============================================================
export const COST_STATUS = {
  market:   ['🟢 خاصة بالسوق', 'text-green-600'],
  unified:  ['🔵 موحّدة', 'text-teal'],
  conflict: ['🟠 تعارض — بانتظار قرارك', 'text-orange-600'],
  missing:  ['🔴 ناقصة', 'text-red-600'],
};
/** [تسمية، صنف CSS] — حالة غير معروفة ← «ناقصة» (السلوك القديم). */
export const costStatusOf = (status) => COST_STATUS[status] || COST_STATUS.missing;
/** هل الحالة تحتاج انتباه المالك (فلتر «الناقصة والمتعارضة»)؟ */
export const needsCostAttention = (status) => status === 'missing' || status === 'conflict';
