-- الدالة كانت تعيد بناء صفوف بجدول جوجل شيت لطلبات كان الفريق نقلها/أرشفها
-- يدوياً (sync_status='failed' بقاعدة البيانات لا يعني الطلب محتاج مزامنة —
-- بعض الطلبات القديمة انتقلت خارج الشيت الحالي عن قصد). أوقفناها فوراً لحد
-- ما نصلّح المنطق (لازم يتحقق أول من وجود الصف قبل ما يعتبره "فاشل يحتاج retry").
-- ============================================================

